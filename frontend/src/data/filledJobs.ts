function buildJob(role: FilledRole): Job {
  const fields = role.fields
  const missing = Object.values(JOB_GROUPS).flat().filter(key => !fields[key])
  if (missing.length) throw new Error(`岗位卡片缺少字段：${missing.join('、')}`)
  const material = `招聘需求沟通纪要\n\n${Object.entries(JOB_GROUPS).map(([group, names]) => `${group}\n${names.map(name => `${name}：${fields[name]}`).join('\n')}`).join('\n\n')}`
  const jd = Object.fromEntries(['岗位职责', '任职要求', '加分条件'].map((name, index) => [name, role.jd[index]]))
  const dimensions = role.dimensions.map(dimension => ({
    label: dimension.label, explanation: dimension.focus, weight: `${dimension.weight}%`,
    anchors: ANCHORS.map((band, index) => `${band}：${[
      `已核实未掌握该维度的基础方法，无法解释${dimension.evidence[0]}；缺证据时标记待评估，不按此档计分`,
      `能描述基础概念，但${dimension.evidence[0]}不清楚，案例行动与证据不足`,
      `能在常规场景说明${dimension.evidence[0]}，部分解释${dimension.evidence[1]}，仍需指导`,
      `可独立完成该维度工作，有完整案例支持${dimension.evidence[1]}，并说明本人职责和限制`,
      `能处理复杂约束，系统说明${dimension.evidence.join('、')}，有可复核结果并提炼改进方法`,
    ][index]}`).join('\n'),
  }))
  const stamp = { version: 1, status: 'draft' as const, source: 'mock' as const, inheritedSources: ['mock' as const], createdAt: '2026-11-14T08:00:00Z', changeReason: '预填岗位资料', unknowns: [] }
  return {
    id: role.id, title: fields['岗位名称'], company: fields['客户企业名称'], location: fields['工作地点'].split('，')[0], salary: fields['转正薪资'].split('，')[0].replace('月薪 ', ''),
    material, materialInput: { kind: 'transcript', transcript: material }, source: 'mock', status: 'draft', version: 0,
    rules: { screening: `${fields['学历要求']}；${fields['经验要求']}；${fields['项目经验']}。缺失或冲突须补证据，不直接判为不符合。`, interview: role.dimensions.map(d => `${d.label}（${d.weight}%）：${d.focus}`).join('\n'), recommendation: '关键能力获得可核实证据，重大冲突已解决；符合确认后的岗位标准，经内部评估和具体版本人工审批后推荐。未覆盖维度标记未评估，不记零分。' },
    documents: [
      { ...stamp, id: `${role.id}-D01`, type: 'D01', title: '岗位画像', tables: profileTables(fields, jd) },
      { ...stamp, id: `${role.id}-D02`, type: 'D02', title: '岗位面试评估表', tables: interviewTables(fields, dimensions) },
    ],
  }
}

export const filledJobs: Job[] = roles.map(buildJob)
